from typing import List

def maxFrequency(nums: List[int], k: int) -> int:
        nums.sort(reverse=True)

        max_frequency = 0

        left_index = 0
        right_index = 0
        while right_index < len(nums):
            k -= nums[left_index] - nums[right_index]

            if k < 0:
                k += ((nums[left_index] - nums[left_index + 1]) * (right_index - left_index))
                left_index += 1

            max_frequency = max(max_frequency, (right_index - left_index) + 1)
            if len(nums) - left_index <= max_frequency:
                 break
            
            right_index += 1

        return max_frequency

